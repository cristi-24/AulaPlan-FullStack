require('dotenv').config();
if(!process.env.JWT_SECRET||process.env.JWT_SECRET.length<32||process.env.JWT_SECRET.startsWith('REEMPLAZAR'))throw new Error('Configura JWT_SECRET con al menos 32 caracteres aleatorios.');
const express=require('express');const cors=require('cors');const path=require('path');const pool=require('./db/pool');
const app=express();app.disable('x-powered-by');
const corsOrigin=process.env.CORS_ORIGIN;app.use(cors(corsOrigin?{origin:corsOrigin}:{}));
app.use(express.json({limit:'20kb'}));
app.use(express.static(path.join(__dirname,'../public')));
app.get('/api/salud',async(req,res,next)=>{try{await pool.query('SELECT 1');res.json({estado:'ok',baseDeDatos:'conectada'});}catch(e){next(e);}});
app.use('/api/auth',require('./routes/auth'));
app.use('/api/tareas',require('./routes/tareas'));
app.use('/api',(req,res)=>res.status(404).json({error:'Ruta API no encontrada.'}));
app.use((err,req,res,next)=>{if(res.headersSent)return next(err);console.error(err);res.status(500).json({error:'Error interno del servidor.'});});
const port=Number(process.env.PORT)||3000;
app.listen(port,()=>console.log(`AulaPlan disponible en http://localhost:${port}`));
